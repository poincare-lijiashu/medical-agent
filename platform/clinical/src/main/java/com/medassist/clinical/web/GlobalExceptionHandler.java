package com.medassist.clinical.web;

import com.medassist.common.api.ErrorCode;
import com.medassist.common.web.AbstractApiExceptionHandler;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.RestControllerAdvice;

/**
 * 临床核心异常映射。
 *
 * <p>语义要点：
 * <ul>
 *   <li>号源已满 / 重复挂号 / 状态机冲突 → <b>409</b>（业务冲突，不是"找不到"）；</li>
 *   <li>就诊、医嘱项目、收费单不存在 → 404；</li>
 *   <li>参数不符合规则 → 422；</li>
 *   <li>EMPI 不可用 → 503（挂号必须失败，客户端应重试而不是"先挂号后补人"）。</li>
 * </ul>
 */
@RestControllerAdvice
public class GlobalExceptionHandler extends AbstractApiExceptionHandler {

    @Override
    protected HttpStatus statusOf(ErrorCode code) {
        return switch (code) {
            case NOT_FOUND, VISIT_NOT_FOUND, ADMISSION_NOT_FOUND, WARD_NOT_FOUND,
                 SURGERY_CASE_NOT_FOUND, PATIENT_NOT_FOUND, ORDER_ITEM_NOT_FOUND,
                 CHARGE_NOT_FOUND, CHARGE_RECEIPT_NOT_FOUND,
                 PATHWAY_TEMPLATE_NOT_FOUND, PATHWAY_INSTANCE_NOT_FOUND,
                 PATHWAY_TASK_NOT_FOUND, DISCHARGE_MED_NOT_FOUND,
                 EMERGENCY_TRIAGE_NOT_FOUND, EMERGENCY_BED_NOT_FOUND,
                 EMERGENCY_OBSERVATION_NOT_FOUND,
                 HEALTH_PACKAGE_NOT_FOUND, HEALTH_REGISTRATION_NOT_FOUND,
                 HEALTH_ITEM_NOT_FOUND, HEALTH_REPORT_NOT_FOUND,
                 CHRONIC_DISEASE_NOT_FOUND, CHRONIC_RECORD_NOT_FOUND, CHRONIC_PLAN_NOT_FOUND,
                 CHRONIC_TASK_NOT_FOUND, CHRONIC_FOLLOWUP_NOT_FOUND,
                 MOBILE_TASK_NOT_FOUND,
                 TRANSFUSION_REQUEST_NOT_FOUND, TRANSFUSION_CROSSMATCH_NOT_FOUND,
                 TRANSFUSION_RECORD_NOT_FOUND,
                 PACU_STAY_NOT_FOUND, OPERATION_LEVEL_NOT_FOUND -> HttpStatus.NOT_FOUND;
            case UNAUTHORIZED -> HttpStatus.UNAUTHORIZED;
            case FORBIDDEN -> HttpStatus.FORBIDDEN;
            case CONFLICT, PATIENT_DUPLICATE, PATIENT_MERGE_CONFLICT,
                 REGISTRATION_NO_SLOT, REGISTRATION_DUPLICATED,
                 VISIT_STATUS_INVALID, ORDER_STATUS_INVALID, CHARGE_STATUS_INVALID,
                 CHARGE_RECEIPT_EXISTS, CHARGE_RECEIPT_STATUS_INVALID,
                 CHARGE_RECEIPT_CHARGE_NOT_PAID,
                 // 转送未完成不是"参数错误"：是流程未走完，语义为业务冲突（结算被拒）
                 ORDER_TRANSFER_INCOMPLETE,
                 DRUG_STOCK_INSUFFICIENT, DRUG_BATCH_EXPIRED,
                 PATHWAY_TEMPLATE_DUPLICATE, PATHWAY_TEMPLATE_STATUS_INVALID,
                 PATHWAY_INSTANCE_EXISTS, PATHWAY_INSTANCE_STATUS_INVALID,
                 PATHWAY_TASK_STATUS_INVALID, PATHWAY_VISIT_INVALID,
                 PATHWAY_INSTANCE_INCOMPLETE,
                 DISCHARGE_MED_STATUS_INVALID, DISCHARGE_MED_EXISTS,
                 DISCHARGE_MED_VISIT_INVALID, DISCHARGE_MED_PRESCRIPTION_MISSING,
                 EMERGENCY_TRIAGE_STATUS_INVALID, EMERGENCY_TRIAGE_NOT_REGISTERED,
                 EMERGENCY_BED_UNAVAILABLE, EMERGENCY_OBSERVATION_STATUS_INVALID,
                 HEALTH_PACKAGE_DUPLICATE, HEALTH_PACKAGE_STATUS_INVALID,
                 HEALTH_REGISTRATION_STATUS_INVALID, HEALTH_ITEM_STATUS_INVALID,
                 HEALTH_REPORT_STATUS_INVALID, HEALTH_REPORT_INCOMPLETE,
                 CHRONIC_RECORD_DUPLICATE, CHRONIC_RECORD_STATUS_INVALID, CHRONIC_PLAN_EXISTS,
                 CHRONIC_PLAN_STATUS_INVALID, CHRONIC_TASK_STATUS_INVALID,
                 MOBILE_TASK_STATUS_INVALID, MOBILE_ADMISSION_INVALID,
                 TRANSFUSION_STATUS_INVALID, TRANSFUSION_CROSSMATCH_INCOMPATIBLE,
                 TRANSFUSION_NOT_CROSSMATCHED, TRANSFUSION_REACTION_EXISTS,
                 PACU_STAY_EXISTS, PACU_STAY_STATUS_INVALID, PACU_OBSERVATION_DUPLICATED,
                 PACU_SELF_SIGN, OPERATION_LEVEL_CONFLICT
                 -> HttpStatus.CONFLICT;
            case VALIDATION_FAILED, CHARGE_RECEIPT_VOID_REASON_REQUIRED,
                 // 补打未登记原因属于“缺必填信息”，422 让前端走原因弹窗而不是报参数错误
                 PRINT_REASON_REQUIRED,
                 PRINT_ANOMALY_NOTE_REQUIRED,
                 PATHWAY_TEMPLATE_INVALID, PATHWAY_TASK_SKIP_REASON_REQUIRED,
                 PATHWAY_EXIT_REASON_REQUIRED, DISCHARGE_MED_INVALID,
                 DISCHARGE_MED_CANCEL_REASON_REQUIRED,
                 EMERGENCY_TRIAGE_LEVEL_INVALID, EMERGENCY_TRIAGE_VITALS_INVALID,
                 EMERGENCY_OUTCOME_INVALID, EMERGENCY_OUTCOME_NOTE_REQUIRED,
                 EMERGENCY_LEAVE_REASON_REQUIRED,
                 HEALTH_PACKAGE_INVALID, HEALTH_REGISTRATION_CANCEL_REASON_REQUIRED,
                 HEALTH_ITEM_RESULT_INVALID, HEALTH_REPORT_INVALID,
                 CHRONIC_PLAN_INVALID, CHRONIC_FOLLOWUP_INVALID,
                 CHRONIC_CLOSE_REASON_REQUIRED, CHRONIC_STOP_REASON_REQUIRED,
                 MOBILE_TASK_INVALID, MOBILE_EXCEPTION_REASON_REQUIRED, MOBILE_SCAN_INVALID,
                 TRANSFUSION_REQUEST_INVALID, TRANSFUSION_CROSSMATCH_INVALID,
                 TRANSFUSION_DOUBLE_CHECK_REQUIRED, TRANSFUSION_REACTION_INVALID,
                 TRANSFUSION_CANCEL_REASON_REQUIRED,
                 PACU_CASE_NOT_ELIGIBLE, PACU_OBSERVATION_TIME_INVALID,
                 PACU_DISCHARGE_NOT_READY, PACU_DESTINATION_INVALID,
                 OPERATION_LEVEL_INVALID
                 -> HttpStatus.UNPROCESSABLE_ENTITY;
            case TOO_MANY_REQUESTS -> HttpStatus.TOO_MANY_REQUESTS;
            case UPSTREAM_UNAVAILABLE -> HttpStatus.SERVICE_UNAVAILABLE;
            case GATEWAY_TIMEOUT -> HttpStatus.GATEWAY_TIMEOUT;
            default -> HttpStatus.BAD_REQUEST;
        };
    }
}
