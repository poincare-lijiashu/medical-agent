-- V99：凭据生命周期与首登强制改密（第 285 批）
--
-- 背景：开通 Cell 时下发的首个管理员口令是"一次性"的，但此前服务端没有任何强制手段。
-- 一份被转发、截图或存进交付单的口令可以长期有效——"一次性"只写在文档里，不是系统事实。
-- 管理员重置口令同理：代为设置的口令是**临时凭据**，不是最终凭据。
--
-- 语义：
--   * must_change_password = true：该口令由他人代设，本人尚未设置自己的口令；
--   * 命中标记仍允许登录（否则首登改密流程无法进行），但控制台会阻断在不可跳过的改密对话框；
--   * 本人改密成功后立即清零；管理员重置/开通首建时置位。
--
-- 刻意不做的：
--   * 口令有效期/历史口令复用（属于 W5 合规章的按院策略，需要可配置，不在本批）；
--   * 标记不参与鉴权：它约束的是"前端交互 + 改密入口"，不是权限位。
-- ============================================================================

ALTER TABLE auth_svc.app_user
    ADD COLUMN IF NOT EXISTS must_change_password boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN auth_svc.app_user.must_change_password IS
    '为 true 时该账号口令是他人代设的临时凭据：登录后必须自行修改，改密成功即清零';
