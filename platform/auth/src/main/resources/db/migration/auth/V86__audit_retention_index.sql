-- ============================================================================
-- V86：审计保留期证据支撑（§267，等保三级「安全审计」）
--
-- 等保三级要求审计日志留存不少于 6 个月，并能证明"没有丢失/没有被提前清理"。
-- change_log 已有追加式触发器（V34），但没有 ts 索引：查最早/最晚审计时间会全表扫描，
-- 测评时在大表上跑证据查询会拖慢生产库。这里补 ts 索引，供保留期证据脚本与运维查询使用。
--
-- 说明：本迁移不删除任何审计数据，也不引入自动清理任务——保留期不足 6 个月时
-- 由证据脚本告警，是否归档/扩容由院方存储策略决定。
-- ============================================================================

CREATE INDEX IF NOT EXISTS ix_change_log_ts
    ON auth_svc.change_log (ts DESC);

COMMENT ON INDEX auth_svc.ix_change_log_ts IS
    '审计保留期证据查询：最早/最晚审计时间（§267）';
