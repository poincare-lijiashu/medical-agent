-- V3：医嘱金额改为可选输入（第 270 批）
--
-- 金额可由「数量 × 单价」推导；模板把 amount 列为必填会让旧系统不导金额的
-- 文件直接卡在预检，属于工具强加的不必要门槛。改为可选，但一旦提供必须与
-- 数量×单价一致（RowNormalizer 强校验），避免"两个金额口径"。
-- ============================================================================

UPDATE mig_svc.mig_field
   SET required = false,
       description = '可省略，由数量×单价计算；提供时必须一致'
 WHERE target_code = 'CLINICAL_ORDER' AND field_key = 'amount';
