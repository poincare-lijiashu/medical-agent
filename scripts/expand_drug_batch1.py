def main():
    d = json.load(io.open(DICT, encoding="utf-8"))
    existed = {x["name"] for x in d}
    added = 0
    for drug in NEW_DRUGS:
        name, aliases, brands, cat, lvl = drug
        if name in existed or name in EXIST:
            continue
        d.append({"name": name, "aliases": aliases, "brand_names": brands,
                  "category": cat, "level": lvl})
        added += 1
    json.dump(d, io.open(DICT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    r = json.load(io.open(RULES, encoding="utf-8"))
    rkeys = {(x["drug_a"], x["drug_b"]) for x in r}
    radded = 0
    for rule in RULES_DST:
        if (rule["drug_a"], rule["drug_b"]) in rkeys:
            continue
        r.append(rule)
        radded += 1
    json.dump(r, io.open(RULES, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"drugs +{added} (total {len(d)}), rules +{radded} (total {len(r)})")


if __name__ == "__main__":
    main()
